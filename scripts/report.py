"""generated/tables.tex and generated/numbers.tex from results/*.csv, results/decisions.json and runs/*.json.
No number, caption or table in the paper is typed by hand: main.tex only \\input{}s these files."""
import json, re, sys
from pathlib import Path
import numpy as np, pandas as pd
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from s2g.config import P, ROOT, LOCS, read_csv, assert_frozen

assert_frozen()
R, G = ROOT / "results", ROOT / "generated"; G.mkdir(exist_ok=True)
for f in ("tables.tex", "numbers.tex"):
    assert not (G / f).exists(), f"{f} exists (written once)"
abl, base, s, kr, w, bs, bt, pc, pr, sq, rn, fl = (read_csv(R / f"{n}.csv") for n in
    ("abl_perseed", "baselines", "summary", "ks_ratio", "wilcoxon", "bootstrap", "baseline_tests", "pct_change", "projection", "seq_level", "run_noise", "ks_floor"))
dec = json.loads((R / "decisions.json").read_text()); gate = json.loads((ROOT / "runs/pilot_gate.json").read_text())
floor = fl.groupby("loc").ks_floor.mean()
cam = lambda s_: "".join(p.capitalize() if not p[:1].isupper() or len(p) == 1 else p for p in re.split(r"_", s_)).replace(" ", "")
MET = dict(ks_stat="Ks", kendall_mae="Tau", acf_mae="Acf", phys_viol_rate="Phys")
LOC = {l: l.capitalize() for l in LOCS}
MODELS = dict(real_val="Real", statd2gan="Stat", timegan="Timegan", rcgan="Rcgan")   # macro names: letters only
pf = lambda p: "<0.001" if p < 1e-3 else f"{p:.3f}"
num, lines = {}, []
esc = lambda t: str(t).replace("_", r"\_")

# ---------------- numbers ----------------
num["nRunsAbl"], num["nRunsBase"] = len(abl), len(base)
num["nPairs"], num["nLocs"], num["nSeeds"] = len(LOCS) * len(P["seeds"]), len(LOCS), len(P["seeds"])
num["nBoot"] = P["inference"]["bootstrap"]["n_boot"]
num["gpuHours"] = f"{(abl.train_seconds.sum() + base.train_seconds.sum()) / 3600:.1f}"
for l in LOCS:
    num[f"ksFloor{LOC[l]}"] = f"{floor[l]:.4f}"
    for c, k in (("full_model", "Full"), ("no_calibration", "NoCal")):
        num[f"ksRatio{k}{LOC[l]}"] = f"{kr[(kr['loc'] == l) & (kr.config == c)].ks_ratio.mean():.2f}"
    num[f"pctNoDSortedTau{LOC[l]}"] = f"{pc[(pc['loc'] == l) & (pc.config == 'no_D_sorted')].kendall_mae.iloc[0]:.0f}"
    pl = pr[pr["loc"] == l]
    for st in ("raw", "cal", "proj"):
        num[f"phys{st.capitalize()}{LOC[l]}"] = f"{pl[f'{st}_phys_viol_rate'].mean():.4f}"
    for mod in MODELS:
        for mt, mn in (("seq_mean_sd", "SeqSd"), ("within_sd", "WithinSd")):
            num[f"{mn}{MODELS[mod]}{LOC[l]}"] = f"{sq[(sq['loc'] == l) & (sq.model == mod)][mt].median():.2f}"
fr = kr[kr.config == "full_model"].groupby("loc").ks_ratio.mean()
num["ksRatioFullMin"], num["ksRatioFullMax"] = f"{fr.min():.2f}", f"{fr.max():.2f}"
for r in w.itertuples():
    k = f"{cam(r.contrast)}{MET[r.metric]}"
    num[f"med{k}"], num[f"pHolm{k}"], num[f"pRaw{k}"] = f"{r.median_diff:.3f}", pf(r.p_holm), pf(r.p_wilcoxon)
for r in bs.itertuples():
    k = f"{cam(r.contrast)}{MET[r.metric]}"; num[f"ciPt{k}"], num[f"ciLo{k}"], num[f"ciHi{k}"] = f"{r.point:.3f}", f"{r.lo:.3f}", f"{r.hi:.3f}"
num["runNoiseDtau"], num["runNoiseBand"] = f"{rn.median_pairwise_abs_dtau.iloc[0]:.3f}", f"{rn.band_pct.iloc[0]:.0f}"
num["dKsMax"] = f"{(pr.proj_ks_stat - pr.cal_ks_stat).abs().max():.4f}"
num["pilotPct"], num["pilotPosSeeds"], num["pilotPassed"] = f"{gate['pct']:.0f}", gate["positive_seeds"], "passed" if gate["passed"] else "did not pass"
yes = lambda d: "holds" if d["holds"] else "does not hold"
num["verdictDOne"], num["verdictDFour"], num["verdictDFive"] = yes(dec["D1"]), yes(dec["D4"]) if dec["D4"] else "not run", yes(dec["D5"])
for a, d in dec["D2"].items(): num[f"verdictComponent{cam(a)}"] = "effective" if d["holds"] else "not distinguishable from the full model"
for m_, d in dec["D6"].items(): num[f"verdictCollapse{cam(m_)}"] = "collapsed" if d["holds"] else "not collapsed"
with open(G / "numbers.tex", "w") as f:
    f.write("% generated by scripts/report.py from results/*.csv; do not edit\n")
    for k, v in sorted(num.items()):
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

# ---------------- tables ----------------
def tab(df, cap, label, fmt=None, small=True):
    fmt, sm = fmt or "l" + "r" * (df.shape[1] - 1), "\\small" if small else ""
    head = " & ".join(esc(c) for c in df.columns) + r" \\"
    body = "\n".join(" & ".join(esc(v) for v in row) + r" \\" for row in df.itertuples(index=False))
    return (f"\\begin{{table}}[t]\n\\centering{sm}\n\\caption{{{cap}}}\n\\label{{{label}}}\n"
            f"\\begin{{tabular}}{{{fmt}}}\n\\toprule\n{head}\n\\midrule\n{body}\n\\bottomrule\n\\end{{tabular}}\n\\end{{table}}\n")

INF = (f"Paired Wilcoxon signed-rank over {len(LOCS) * len(P['seeds'])} (location, seed) pairs, two-sided; "
       "Holm step-down adjustment (monotone) within each metric family.")
# floor / KS ratio
t = pd.DataFrame({"Location": [LOC[l] for l in LOCS], "Reference": [f"{floor[l]:.4f}" for l in LOCS],
                  "Full model (ratio)": [f"{fr[l]:.2f}" for l in LOCS],
                  "No calibration (ratio)": [f"{kr[(kr['loc'] == l) & (kr.config == 'no_calibration')].ks_ratio.mean():.2f}" for l in LOCS]})
lines.append(tab(t, "KS sup-distance relative to the real train versus held-out reference (mean over "
                 f"{len(P['seeds'])} seeds). The reference is the mean over the {len(P['data']['scalable_idx'])} scalable features of the KS "
                 "distance between real training and real held-out marginals. It is a practical reference, not a mathematical lower bound.", "tab:floor"))
# main per-metric tables
names = {"ks_stat": "KS sup-distance", "kendall_mae": "Kendall tau MAE", "acf_mae": "ACF MAE", "phys_viol_rate": "Physics violation rate"}
for mt, nm in names.items():
    t = pd.DataFrame({"Arm": s.config.unique()})
    for l in LOCS:
        q = s[s["loc"] == l].set_index("config")
        t[LOC[l]] = [f"{q.loc[a, mt + '_mean']:.3f} $\\pm$ {q.loc[a, mt + '_std']:.3f}" for a in t.Arm]
    lines.append(tab(t, f"{nm} (mean $\\pm$ SD over {len(P['seeds'])} seeds, held-out).", f"tab:{mt}"))
# inference
def wt(df, cap, label):
    t = df[["metric", "contrast", "median_diff", "p_wilcoxon", "p_holm", "pos_by_loc"]].copy()
    t["median_diff"] = t.median_diff.map("{:.4f}".format); t["p_wilcoxon"] = t.p_wilcoxon.map(pf); t["p_holm"] = t.p_holm.map(pf)
    t.columns = ["Metric", "Contrast", "Median diff", "p", "p (Holm)", "Positive pairs by location"]
    return tab(t, cap, label, "llrrrl")
lines.append(wt(w, INF + " Difference = arm minus full model on the same seed.", "tab:wilcoxon"))
lines.append(wt(bt, INF + " Baselines against the full model, family of two.", "tab:baselines"))
b2 = bs.copy(); b2[["point", "lo", "hi"]] = b2[["point", "lo", "hi"]].map("{:.4f}".format)
lines.append(tab(b2.rename(columns=str.capitalize),
                 f"Location-clustered bootstrap of the paired difference. Statistic: mean over the {len(LOCS)} locations of the per-location "
                 f"median of {len(P['seeds'])} paired seed differences; locations resampled with replacement, {P['inference']['bootstrap']['n_boot']} draws, "
                 "percentile 95\\% interval. With five clusters the interval is coarse.", "tab:bootstrap"))
# projection and sequence level
t = pr.groupby("loc")[["raw_phys_viol_rate", "cal_phys_viol_rate", "proj_phys_viol_rate", "cal_ks_stat", "proj_ks_stat"]].mean().loc[LOCS]
t = t.map("{:.4f}".format).reset_index(); t["loc"] = t["loc"].map(LOC); t.columns = ["Location", "Viol. raw", "Viol. calibrated", "Viol. projected", "KS calibrated", "KS projected"]
lines.append(tab(t, "Physics violation rate and KS sup-distance for the full model: raw generator output, after calibration, after projection (mean over seeds).", "tab:projection"))
t = sq.groupby(["loc", "model"])[["seq_mean_sd", "within_sd"]].median().unstack("model")
t.columns = [f"{a} ({b})" for a, b in t.columns]; t = t.loc[LOCS].map("{:.2f}".format).reset_index(); t["loc"] = t["loc"].map(LOC)
lines.append(tab(t.rename(columns={"loc": "Location"}), "Sequence-level temperature statistics (C), median over seeds; real = held-out sequences. seq\\_mean\\_sd: SD of per-sequence means; within\\_sd: mean within-sequence SD.", "tab:seq", small=True))
# pilot + manifest
lines.append(tab(pd.DataFrame([dict(Rule=P["pilot"]["gate"], Pct=f"{gate['pct']:.1f}", PositiveSeeds=f"{gate['positive_seeds']}/{gate['n_seeds']}", Outcome=num["pilotPassed"])]),
                 "Pre-declared pilot gate (Dubai) and its outcome.", "tab:pilot", "p{7cm}rrl"))
(G / "tables.tex").write_text("% generated by scripts/report.py; do not edit\n" + "\n".join(lines))
print(f"wrote {len(num)} macros and {len(lines)} tables")
